# 1. Integer Literal
a = 100
print(a)

# 2. Float Literal
b = 10.5
print(b)

# 3. Complex Literal
c = 2 + 3j
print(c)

# 4. String Literal
name = "Sakshi"
print(name)

# 5. Boolean Literal
x = True
y = False
print(x)
print(y)

# 6. None Literal
z = None
print(z)

# 7. List Literal
numbers = [10, 20, 30]
print(numbers)

# 8. Tuple Literal
numbers = (10, 20, 30)
print(numbers)

# 9. Set Literal
numbers = {10, 20, 30}
print(numbers)

# 10. Dictionary Literal
student = {"name": "Sakshi", "age": 16}
print(student)